"""Draw the five-study evidence matrix from BeeTrack's released replay bundles.

Run from the project root. Supply --report117 with the JSON generated by
tools/study117/release117.py replay docs/study117_replay.json.gz --report FILE.
Use --pending117 only for a draft which explicitly omits that study's outcome.
"""
import argparse
import gzip
import json
from pathlib import Path
from statistics import mean
import sys

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib import font_manager
from matplotlib.lines import Line2D
from matplotlib.patches import Rectangle


INK, GRAY, TEAL, WARM = '#1E3544', '#526975', '#006F6D', '#9F4B21'


def read_gz(path):
    with gzip.open(path, 'rt', encoding='utf8') as file:
        return json.load(file)


def evidence(root, temporal):
    for study in (113, 114, 115, 116):
        sys.path.insert(0, str((root / f'tools/study{study}').resolve()))
    import release113, release115, release116

    docs = root / 'docs'
    _, m113 = release113.replay(read_gz(docs / 'study113_replay.json.gz'), docs / 'study108_source.json.gz')
    m114 = read_gz(docs / 'study114_replay.json.gz')['summary']
    m115 = release115.load_archive(docs / 'study115_replay.json.gz')['roles']['target']['scores']
    m116 = release116.replay(release116.scalar_codec(read_gz(docs / 'study116_replay.json.gz'), inverse=True))
    data = {}
    for hive in (33, 35):
        fold = str(68 - hive)
        a = m113['hives'][str(hive)]
        assessable = sum(s['counts'][d]['assessable'] for s in a['seeds'] for d in ('in', 'out'))
        assert len(a['seeds']) == 9 and not a['eligible_for_followup']
        gates = list(m114['seed_gates'][fold].values())
        enough = [g['tail_bees'] for g in gates]
        gains = [g['gain'] * 100 for g in gates]
        assert len(gates) == 3 and not m114['fold_gates'][fold]['passes']
        g115 = [m115['groups'][f'{hive}_{s}_head'] for s in (0, 3, 6)]
        delta = mean(g['count']['integer_minus_e3_pp'] for g in g115)
        f1 = mean(g['0.5']['f1']['geometry'] - g['0.5']['f1']['canonical'] for g in g115)
        n = m116['visibility']['clips'][f'BEE24-{hive}-tail']
        assert n['n'] == 16 and len(n['seeds']) == 3 and not n['gate']['passes']
        cells = [r['views']['original']['0.5'] for r in n['seeds'].values()]
        losses = [c['regions']['U']['outside']['tp'] - c['regions']['L']['outside']['tp'] for c in cells]
        assert min(losses) > 0 and a['total_m'] == 0 and a['mean_cap_pp'] == 0
        ret = (f'四特徵較距離多 {min(gains):.2f}–{max(gains):.2f} 點' if min(enough) >= 10 else
               f'每個 seed 僅能比較 {min(enough)}–{max(enough)} 隻蜂')
        data[hive] = [
            (f'{a["total_m"]} / {assessable:,} 次碰到地標', '窗誤差最多改善 0 點'),
            (ret, f'達預設條件 {sum(g["passes"] for g in gates)} / 3 個 seed'),
            (f'整數窗誤差較 E3 {delta:+.2f} 點', f'幾何較固定代表 F1 {f1:+.4f}'),
            (f'{len(n["gate"]["passing_seeds"])} / 3 個 seed 達標', f'各 seed 在入口矩形外多漏 {min(losses)}–{max(losses)} 框'),
        ]
        if temporal:
            cases = temporal['cases'][f'BEE24-{hive}-tail']
            assert set(cases) == {'0', '1', '2'}
            dw = mean(c['A']['w30_percent'] - c['U']['w30_percent'] for c in cases.values())
            df = mean(c['A']['iou']['0.5']['f1'] - c['U']['iou']['0.5']['f1'] for c in cases.values())
            identical=all(c['A']['w30_percent']==c['U']['w30_percent'] and c['A']['iou']['0.5']['f1']==c['U']['iou']['0.5']['f1'] for c in cases.values())
            data[hive].append(('三個 seed 都與原生同分',f'平均 W {mean(c["U"]["w30_percent"] for c in cases.values()):.2f}%') if identical else
                              (f'窗誤差 {dw:+.2f} 點', f'官方事件 F1 {df:+.4f}'))
        else:
            data[hive].append(('待公開三個 seed 的全片 W、F1', '來源尾段；留出蜂箱另作驗證'))
    return data


def plot(data, out, temporal):
    fonts = {f.name for f in font_manager.fontManager.ttflist}
    plt.rcParams['font.family'] = next(f for f in ('Microsoft JhengHei', 'Noto Sans CJK TC', 'Noto Sans TC', 'PingFang TC') if f in fonts)
    fig = plt.figure(figsize=(16, 9), facecolor='white')
    def txt(x, y, s, size=13, color=INK, bold=False):
        fig.text(x, y, s, fontsize=size, color=color, va='center', fontweight='bold' if bold else 'normal')
    def rule(y):
        fig.add_artist(Line2D((.042, .962), (y, y), transform=fig.transFigure, color='#D1DEE0', lw=.9))

    txt(.041, .94, '五個實驗，哪些證據能用在未參與訓練的蜂箱？', 26, bold=True)
    txt(.043, .873, '每列比較同一問題、同一影片。只有整數事件實驗直接驗證兩個留出蜂箱。', 16, GRAY)
    for x, s in ((.044, '問題與評估資料'), (.342, '蜂箱 33'), (.597, '蜂箱 35'), (.838, '研究決定')):
        txt(x, .797, s, 14, bold=True)
    rule(.759)
    titles = [('固定地標能刪錯誤進出？', '§113　來源前段 · 9 個 seed'),
              ('能辨認同蜂折返？', '§114　來源前段擬合、尾段評分 · 3 個 seed'),
              ('三路平均能輸出整數事件？', '§115　留出前段 · 3 組各 3 個 seed'),
              ('多給入口像素能看全穿越？', '§116　來源尾段 · 各 16 隻蜂、3 個 seed'),
              ('借前兩幀特徵能幫計數？', '§117　來源尾段 · 全片、3 個 seed')]
    decisions = [('停止固定', '地標刪除規則'), ('暫不接入', '全片追蹤器'), ('保留整數計數', '身分選擇未達標'), ('停止固定倍率', '入口放大'), ('待評分', '尚未驗留出片')]
    if temporal:
        folds = list(temporal['folds'].values())
        advance = all(f['utility']['passed'] and f['complexity']['passed'] for f in folds)
        decisions[-1] = ('另登記留出驗證', '來源通過效用對照') if advance else ('止於來源驗證', '全片增益未達標')
    for i, ((title, scope), decision) in enumerate(zip(titles, decisions)):
        y = .699 - i * .123
        if i == 2:
            fig.add_artist(Rectangle((.040, y-.066), .924, .122, transform=fig.transFigure, facecolor='#EDF6F3', linewidth=0, zorder=-2))
        txt(.044, y+.007, title, 16, bold=True)
        txt(.045, y-.035, scope, 10.7, TEAL if i==2 else GRAY)
        for x,h in ((.342,33),(.597,35)):
            a,b = data[h][i]
            txt(x, y+.007, a, 13.5, bold=i==2)
            txt(x, y-.035, b, 11.5, GRAY)
        txt(.838, y+.007, decision[0], 14, TEAL if i==2 else WARM, True)
        txt(.838, y-.035, decision[1], 11.5, GRAY)
        rule(y-.066)
    txt(.044, .111, 'W 為 30 秒分向窗計數誤差，越低越好。F1 用官方 IoU 0.5，越高越好。§117 以位移對齊減原生 640。', 12, GRAY)
    txt(.044, .069, '來源 33 用 no35，來源 35 用 no33。相同蜂箱內各 seed 共用影片和真蜂。資料來自 BeeTrack §113–117 公開重播。' if temporal else
        '來源 33 用 no35，來源 35 用 no33。相同蜂箱內各 seed 共用影片和真蜂。§113–116 為公開重播；§117 尚待定稿。', 11.1, GRAY)
    fig.savefig(out, dpi=160, facecolor='white')
    plt.close(fig)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--repo', type=Path, default=Path.cwd())
    p.add_argument('--output', type=Path, default=Path(__file__).with_suffix('.png'))
    stage = p.add_mutually_exclusive_group(required=True)
    stage.add_argument('--report117', type=Path)
    stage.add_argument('--pending117', action='store_true')
    a = p.parse_args()
    temporal = json.loads(a.report117.read_bytes()) if a.report117 else None
    plot(evidence(a.repo, temporal), a.output, temporal)


if __name__ == '__main__':
    main()
